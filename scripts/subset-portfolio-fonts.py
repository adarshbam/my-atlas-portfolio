"""Subset existing fonts to the portfolio's characters, retaining full fallbacks.

Maintenance only: pip install --target tmp/fonttools fonttools brotli
"""
from pathlib import Path
import json
import sys

root = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(root / "tmp/fonttools"))
from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.pens.recordingPen import DecomposingRecordingPen

characters = set(range(32, 127))
for path in (root / "src").rglob("*"):
    # Data files and CSS-generated labels also contribute visible characters.
    if path.suffix in [".ts", ".tsx", ".json", ".css"]:
        characters.update(ord(char) for char in path.read_text(encoding="utf-8") if ord(char) >= 32)
characters.update(ord(char) for char in (root / "index.html").read_text(encoding="utf-8") if ord(char) >= 32)

css, reports = [], []
for family, weight, source_name, target_name in [
    ("Cormorant Garamond", 500, "cormorant-garamond-latin-500-normal", "cormorant-garamond-portfolio-500"),
    ("EB Garamond", 400, "eb-garamond-latin-400-normal", "eb-garamond-portfolio-400"),
]:
    source = root / f"public/fonts/{source_name}.woff2"
    target = root / f"public/fonts/{target_name}.woff2"
    original = TTFont(source)
    codes = sorted(characters.intersection(original.getBestCmap()))
    options = subset.Options()
    options.flavor = "woff2"
    options.name_IDs = list(range(26))
    font = subset.load_font(str(source), options)
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=codes)
    subsetter.subset(font)
    subset.save_font(font, str(target), options)
    reduced = TTFont(target)
    for code in codes:
        outlines, widths = [], []
        for face in [original, reduced]:
            name = face.getBestCmap()[code]
            glyphs = face.getGlyphSet()
            pen = DecomposingRecordingPen(glyphs)
            glyphs[name].draw(pen)
            outlines.append(pen.value)
            widths.append(face["hmtx"][name])
        assert outlines[0] == outlines[1], f"Outline changed: {family} {chr(code)}"
        assert widths[0] == widths[1], f"Metrics changed: {family} {chr(code)}"
    ranges = []
    for code in codes:
        if ranges and code == ranges[-1][1] + 1:
            ranges[-1][1] = code
        else:
            ranges.append([code, code])
    unicode_range = ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in ranges)
    css.append(f'''@font-face {{
  font-family: "{family}";
  src: url("/fonts/{target_name}.woff2") format("woff2");
  font-weight: {weight};
  font-display: swap;
  unicode-range: {unicode_range};
}}''')
    reports.append({"family": family, "weight": weight, "sourceBytes": source.stat().st_size,
                    "subsetBytes": target.stat().st_size, "verifiedCharacters": len(codes),
                    "outlinesAndMetricsUnchanged": True})
(root / "src/styles/font-subsets.css").write_text(
    "/* Generated by scripts/subset-portfolio-fonts.py. Full faces remain as Unicode fallbacks. */\n" + "\n".join(css) + "\n", encoding="utf-8")
print(json.dumps(reports, indent=2))
